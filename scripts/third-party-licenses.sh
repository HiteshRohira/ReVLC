#!/usr/bin/env bash
# Writes the licences of the dependencies compiled into ReVLC to
# licenses/THIRD-PARTY-RUST.txt and licenses/THIRD-PARTY-JS.txt, which the
# app bundles. Run it after changing dependencies, and commit the result.
#
# Needs cargo-about: cargo install cargo-about --locked --features cli
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/licenses"

# Rust: crates linked into the app on macOS, Windows and Linux (scripts/about.toml).
(cd "$ROOT/src-tauri" && cargo about generate --locked --fail \
  -c "$ROOT/scripts/about.toml" "$ROOT/scripts/about.hbs" -o "$OUT/THIRD-PARTY-RUST.txt")

# JavaScript: the packages that end up in the UI bundle, read from a
# throwaway build's source maps (most of node_modules is build tooling).
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
(cd "$ROOT" && npx vite build --sourcemap --outDir "$tmp" --emptyOutDir --logLevel error)
node - "$tmp" "$ROOT" "$OUT/THIRD-PARTY-JS.txt" <<'EOF'
const fs = require("fs");
const path = require("path");
const [dist, root, out] = process.argv.slice(2);

// Packages that ship only an SPDX file: same licence and copyright holder as
// the package named here.
const SAME_AS = { "@tauri-apps/plugin-dialog": "@tauri-apps/api" };

const names = new Set();
for (const file of fs.readdirSync(path.join(dist, "assets"))) {
  if (!file.endsWith(".map")) continue;
  for (const src of JSON.parse(fs.readFileSync(path.join(dist, "assets", file))).sources) {
    const m = src.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    if (m) names.add(m[1]);
  }
}

const licenceFiles = (name) => {
  const dir = path.join(root, "node_modules", name);
  return fs.readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f) && !f.endsWith(".spdx"))
    .sort()
    .map((f) => fs.readFileSync(path.join(dir, f), "utf8").trim());
};

let text = "Third-party licences: JavaScript packages compiled into ReVLC.\n" +
  "Generated by scripts/third-party-licenses.sh; don't edit by hand.\n";
for (const name of [...names].sort()) {
  const pkg = require(path.join(root, "node_modules", name, "package.json"));
  const texts = licenceFiles(name).length ? licenceFiles(name) : licenceFiles(SAME_AS[name] ?? name);
  if (!texts.length) throw new Error(`No licence text found for ${name}`);
  text += `\n${"=".repeat(80)}\n${name} ${pkg.version} (${pkg.license})\n${"-".repeat(80)}\n\n`;
  text += texts.join("\n\n") + "\n";
}
fs.writeFileSync(out, text);
console.log(`${out}: ${names.size} packages`);
EOF
echo "$OUT/THIRD-PARTY-RUST.txt"
